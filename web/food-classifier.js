export function classifyFoodName(value) {
  const name = foodNameKey(value);
  const invalid =
    !name ||
    /[<>]|https?:\/\/|www\.|[\u0000-\u001f]/i.test(name) ||
    (/^[\d\s\W_]+$/u.test(name) && !/[\p{L}]/u.test(name));
  if (invalid || excluded.some((matches) => matches(name)))
    return {
      status: "non_food",
      category: "other",
      ingredient: "",
      source: "rules",
    };
  // Prefer full, specific phrases (soy milk, fish sauce, fried rice) over generic ingredients.
  const matching = rules.filter((rule) => rule.matches(name));
  const first = matching.find((rule) => rule.term === name) || matching[0];
  const uncertainCompound =
    first &&
    first.term !== name &&
    (new Set(matching.map((rule) => rule.category)).size > 1 ||
      /[\u3400-\u9fff]/.test(first.term));
  if (uncertainCompound)
    return {
      status: "uncertain",
      category: "other",
      ingredient: "",
      source: "rules",
    };
  const shortNames = {
    蛋: ["dairy", "egg"],
    米: ["dry", "rice"],
    油: ["condiments", "oil"],
    鹽: ["condiments", "salt"],
    盐: ["condiments", "salt"],
    茶: ["other", ""],
    水: ["other", ""],
    魚: ["protein", ""],
    鱼: ["protein", ""],
    肉: ["protein", ""],
    飯: ["cooked", "rice"],
    饭: ["cooked", "rice"],
  };
  if (!first && Object.hasOwn(shortNames, name))
    return {
      status: "food",
      category: shortNames[name][0],
      ingredient: shortNames[name][1],
      source: "rules",
    };
  if (!first)
    return {
      status: "uncertain",
      category: "other",
      ingredient: "",
      source: "rules",
    };
  const ingredient =
    Object.entries(ingredientAliases).find(([, terms]) =>
      terms.some((term) => name === term),
    )?.[0] || "";
  return {
    status: "food",
    category: first.category,
    ingredient,
    source: "rules",
  };
}
export function validateFoodAssessment(raw) {
  if (
    !raw ||
    !["food", "non_food", "uncertain"].includes(raw.status) ||
    !["high", "medium", "low"].includes(raw.confidence)
  )
    throw Error("invalid_assessment");
  const validCategory = groups.some(([category]) => category === raw.category);
  if (raw.status === "food" && !validCategory)
    throw Error("invalid_assessment");
  const status = raw.confidence === "high" ? raw.status : "uncertain";
  return {
    status,
    category: validCategory ? raw.category : "other",
    ingredient: Object.hasOwn(ingredientAliases, raw.ingredient)
      ? raw.ingredient
      : "",
    source: "deepseek",
  };
}
