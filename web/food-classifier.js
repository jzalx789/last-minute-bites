function matcher(term) {
  if (/[\u3400-\u9fff]/.test(term)) return (name) => name.includes(term);
  const regex = new RegExp(
    "(^|[^a-z0-9])" +
      term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") +
      "([^a-z0-9]|$)",
  );
  return (name) => regex.test(name);
}
const excluded = nonFoods.map(matcher);
const rules = groups
  .flatMap(([category, terms], order) =>
    terms.map((term) => ({ category, term, order, matches: matcher(term) })),
  )
  .sort((a, b) => b.term.length - a.term.length || a.order - b.order);
